// @ts-check

import fs from 'node:fs';
import path from 'node:path';

// This runs in Node.js - Don't use client-side code here (browser APIs, JSX...)

// Read fresh at build time (not cached) so a later /document run that
// regenerates docs/_sidebar.docsolace.json (new tour, new product page, a
// tour archived into docs/archive/) is picked up on the site's next build
// with no further edit needed here. Written by generate-product-docs.mjs —
// see the DocSolace plugin's "Document the product itself"/"Scaffold a docs
// site" recipe.
const sidebarDataPath = path.join(process.cwd(), '..', 'docs', '_sidebar.docsolace.json');
const sidebarData = JSON.parse(fs.readFileSync(sidebarDataPath, 'utf8'));

const archiveDir = path.join(process.cwd(), '..', 'docs', 'archive');
const hasArchive = fs.existsSync(archiveDir);

/**
 * Creating a sidebar enables you to:
 - create an ordered group of docs
 - render a sidebar for each doc of that group
 - provide next/previous navigation

 The sidebars can be generated from the filesystem, or explicitly defined here.

 Create as many sidebars as you want.

 @type {import('@docusaurus/plugin-content-docs').SidebarsConfig}
 */
const sidebars = {
  tutorialSidebar: [
    ...sidebarData.productPages,
    ...sidebarData.sections.map((section) => ({
      type: 'category',
      label: section.label,
      items: section.tours,
    })),
    ...sidebarData.unsectionedTours,
    ...(hasArchive
      ? [
          {
            type: 'category',
            label: 'Archive',
            items: [{type: 'autogenerated', dirName: 'archive'}],
          },
        ]
      : []),
  ],
};

export default sidebars;
